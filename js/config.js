/* =========================================================
   config.js — ゲームバランスの全パラメータと、その設計思想
   ---------------------------------------------------------
   このゲームの狙いは「敵がどんどん増え、それ以上に自分が強くなる」こと。
   難しさは上げてよい。ただし上げ方に条件をつける。

     難易度の伸び < 火力の伸び

   この不等式さえ守られていれば、敵が増えても画面は制圧しやすくなり、
   爽快感は下がらない。逆にこれが破れると、ただの理不尽なゲームになる。
   だから難易度側の上昇は 1 か所（CFG.curve）に集約し、
   上限つき・線形・緩やかに、という 3 つの縛りをかけてある。

   実際の伸び（実効ウェーブ 0 → 上限到達まで）:
     敵の湧く量   1.5 → 62 匹/秒   （約 41 倍）
     自機の火力   約 10 → 約 190 DPS（約 19 倍）  ← 一番伸びる
     撃ってくる敵  8  → 34 体      （約 4.3 倍）
     敵弾の上限   18  → 62 発      （約 3.4 倍）
     重装敵の HP  ×1.0 → ×2.6      （約 2.6 倍）
     敵弾の速さ   120 → 188 px/秒  （約 1.6 倍）

   脅威は「経過時間」だけでなく「自機の装備の充実度」にも連動する
   （CFG.threatWave）。時間だけに紐づけると、装備が揃うほど一方的になり、
   パワーアップするたびに手応えが消えて作業になってしまうため。

   難易度側の数値（CFG.curve）はどれも上限つきなので、
   何分やっても際限なく難しくなることはない。

   一方、以下は最後まで固定する。ここを動かすと質的に別のゲームになるため。

     ・ザコの HP … 1〜2 のまま。全体を硬くすると武器を強化した手応えが
                   そのまま消える。硬くするのは撃ち込む対象（重装敵）だけ。
     ・敵弾は必ず自機より遅い … 反応ではなく位置取りで避けられる状態を保つ。
     ・ミス時のペナルティ … オプション 1 個だけ。グラディウス式の全ロストは
                            ミスした瞬間に難易度が跳ね上がる典型的な罠。
   ========================================================= */
(function (w) {
  'use strict';

  var CFG = {
    /* ---------- 画面 ---------- */
    W: 640,            // 論理解像度（CSS で拡大表示する）
    H: 400,
    FPS: 60,
    DT: 1 / 60,        // 固定タイムステップ（1 フレームの秒数）

    /* ---------- 自機 ---------- */
    player: {
      x: 90, y: 200,
      r: 3.5,          // 当たり判定半径。見た目より小さい（被弾ストレスを下げる）
      drawR: 12,
      baseSpeed: 195,  // px/秒
      speedStep: 32,   // SPEED を 1 段取るごとの上昇量
      speedMax: 6,     // SPEED の最大段数
      slowRate: 0.42,  // Shift 低速時の倍率
      invincible: 2.4, // ミス後の無敵秒数
      respawn: 0.9,    // ミス後の復帰待ち秒数
      shieldGrace: 0.5 // バリアで 1 発受けたあとの短い無敵秒数
    },

    /* ---------- 自機の武器 ---------- */
    weapon: {
      fireInterval: 0.105,   // ショット間隔（秒）
      fireIntervalMin: 0.062,// チェイン最大時の間隔。ここまで速くなる
      bulletSpeed: 660,
      bulletDamage: 1,

      /* 装備はどれも多段階。1 段ごとに手応えが変わるように、
         「弾の数が増える段」と「威力が上がる段」を交互に配置してある。
         同じ段数でも伸びが単調にならないようにするため。

         レーザーは廃止した。貫通する一本の線は、
         並んだ敵をまとめて貫いてしまうぶん他の武器より明確に強く、
         しかも画面を覆って敵と敵弾を隠す。
         代わりに「数で押す」3 系統に置き換えてある。
           VULCAN  … 正面に広がる拡散弾。手数の土台
           HOMING  … 曲がって追いかける弾の群れ。散った敵に強い
           CLUSTER … 着弾で爆発し、破片を全方位に撒く。固まった敵に強い
         どれも排他ではなく、取ったぶんだけ同時に撃つ */
      vulcanMax: 6,          // 2way→3way→威力→5way→威力→7way
      homingMax: 6,          // 1発→2発→威力→4発→威力→6発
      homingInterval: 0.30,
      clusterMax: 6,         // 1発→範囲→2発→破片増→威力→3発
      clusterInterval: 0.85,

      optionMax: 6,          // オプション（マルチプル）最大数
      optionGap: 10,         // オプション同士の距離（自機の軌跡を何フレーム遡るか）
      optionAngles: 3,       // オプション 1 基が撃つ弾の本数上限。
                             // 本体と同じだけ撃たせると 6 基で弾が数十発になり、
                             // 画面が自弾で埋まって敵も敵弾も見えなくなる

      forceMax: 5,           // フォースフィールドの段数
      shieldHits: [3, 5, 7, 9, 12]  // 各段での耐弾数
    },

    /* パワーメーター（グラディウス方式）のスロット。
       カプセルを取るとカーソルが 1 つ進み、X で発動して消費する。 */
    slots: [
      { key: 'speed',   label: 'SPEED',   color: '#7fe3ff' },
      { key: 'cluster', label: 'CLUSTER', color: '#ffd45e' },
      { key: 'vulcan',  label: 'VULCAN',  color: '#7dff9a' },
      { key: 'homing',  label: 'HOMING',  color: '#ff7ad1' },
      { key: 'option',  label: 'OPTION',  color: '#b79cff' },
      { key: 'force',   label: 'FORCE',   color: '#ff8f5e' }
    ],

    /* ---------- チェイン（連鎖） ---------- */
    chain: {
      hold: 2.0,        // 最後の撃破からこの秒数で連鎖が切れる
      max: 300,         // 表示・計算上の上限
      rateAt: 120,      // この連鎖数で連射速度が最大になる
      side1: 30,        // この連鎖数から上下へサイドショット追加
      side2: 90,        // さらに追加
      scoreStep: 25     // 25 連鎖ごとに得点倍率 +1
    },

    /* ---------- ボム ---------- */
    bomb: {
      start: 2,
      max: 5,
      damage: 40,       // 画面内の敵全体に与えるダメージ
      duration: 0.8
    },

    /* =========================================================
       ▼ ここから下が脅威側の設定
       ========================================================= */

    threat: {
      /* 予算の何割まで埋まったら発射を渋り始めるか。
         敵が 200 匹いても全員が同時に撃つわけではない、を作る仕組み。
         上限そのものは curve でゆっくり引き上げる */
      softCapRatio: 0.7,

      /* 敵が密集しすぎたときに自機の周囲へは湧かせない安全半径 */
      spawnSafeR: 96
    },

    /* =========================================================
       難易度カーブ。難しくなる要素はすべてここに集約してある。
       どれも線形・上限つき。いじるならここだけ見れば足りる。
       ========================================================= */
    curve: {
      /* 画面に出せる敵弾の総数。これが難易度の主スイッチ */
      budget:   { base: 18,   per: 1.60,   max: 62 },
      /* 敵弾の速さ(px/秒)。自機の最低速度 195 は超えさせない。
         超えると「見てから避ける」が成立せず、質の違う難しさになる */
      speed:    { base: 120,  per: 3.00,   max: 188 },
      /* 狙い撃ちのブレ幅(rad)。小さいほど正確＝難しい */
      aim:      { base: 0.20, per: -0.006, min: 0.06 },
      /* 撃ってくる敵の画面内上限。超える分はザコに差し替わる */
      armed:    { base: 8,    per: 0.95,   max: 34 },
      /* 重装敵（HP 10 以上）だけに掛かる HP 倍率。
         ザコの HP は 1〜2 のまま動かさない。
         全体を硬くすると「武器を強くした手応え」がそのまま消えるが、
         撃ち込み対象だけを硬くするぶんには、雑魚を薙ぎ払う快感は残る */
      tough:    { base: 1.0,  per: 0.075,  max: 2.6 },
      /* 編隊が「撃ってくる／硬い」型になる確率。
         数の暴力だけでは火力が伸びた側が一方的に強くなるので、
         進むほど “撃ち返してくる相手” の比率そのものを上げる */
      armedMix: { base: 0.10, per: 0.035,  max: 0.66 }
    },

    /* ---------------------------------------------------------
       装備に連動した脅威（いわゆるラバーバンド）。

       脅威を時間だけに紐づけると、火力の伸び（約 19 倍）に対して
       脅威の伸びが小さすぎて、パワーアップするほど楽になってしまう。
       そこで「実効ウェーブ = 経過ウェーブ + 装備の充実度 × この値」とし、
       フル装備なら 13 ウェーブぶん先の脅威と戦うことにする。

       注意：上げすぎると「強くなったら罰される」感覚になる。
       火力の伸びのほうが依然として大きいことが前提の補正値。
       --------------------------------------------------------- */
    threatFromPower: 13,

    /* ---------- 敵の湧き（ディレクター） ---------- */
    director: {
      waveSeconds: 16,      // この秒数ごとに「密度」が 1 段上がる
      baseInterval: 2.0,    // 編隊を出す間隔（秒）
      intervalFloor: 0.42,  // どれだけ詰まってもこれ以上は速くしない
      intervalDecay: 0.865, // ウェーブごとに間隔へ掛ける係数
      baseCount: 3,         // 1 編隊あたりの初期数
      countPerWave: 1.6,    // ウェーブごとの増加数
      countMax: 26,         // 1 編隊の最大数

      /* 画面内の敵の最大数。
         体当たりが自機を壊す以上、この値は「処理落ち防止」ではなく
         難易度そのものになる。密度が自機の火力で掃ける量を超えると
         立つ場所が無くなり、腕前と無関係に事故死するだけのゲームになる。
         中盤の火力（約 70 DPS）で捌ける量から逆算してある */
      aliveMax: 190,
      bossEvery: 6          // このウェーブ数ごとに大型艦（ご褒美タイム）
    },

    /* ---------- アイテム ---------- */
    item: {
      /* ---------------------------------------------------------
         カプセルの供給設計。
         「1 個の重みを上げて、数をぐっと減らす」方針。
         画面を埋めるのは敵であってアイテムではない。

         必要数の目安：装備をひと通り最大にするのに約 84 個
         （SPEED6=6 + CLUSTER6=12 + VULCAN6=18 + HOMING6=24 + OPTION6=30）。
         下の設定だと 1 個あたり最短 2.4 秒なので、
         だいたい 5〜6 分でフル装備に届く計算になる。
         --------------------------------------------------------- */

      /* 何匹倒すごとに 1 個出るか。ウェーブが進むほど必要数を増やす。
         終盤は毎秒 90 匹倒すので、固定値のままだとアイテムが洪水になる。
         「敵が増えるほど 1 個が遠くなる」ことで供給レートが平らになる。
         ただし硬い敵が増えると撃破数そのものが伸びなくなるので、
         重装敵は撃破時に個別にカプセルを落とす（capChance）。
         「硬い相手を倒したぶんだけ強くなる」という手応えも兼ねている */
      killsPerCapsule: { base: 10, per: 1.8, max: 34 },

      /* 最短でもこの間隔を空ける。供給レートの天井 */
      capsuleMinInterval: 1.6,
      /* 画面内に同時に存在できる数 */
      capsuleOnScreenMax: 4,
      /* ベルの画面内上限 */
      bellOnScreenMax: 3,

      /* 左へ流れる速さ。数を増やさずに供給量を上げたいときはここを速くする。
         画面内の枠（4 個）が空くのが早くなるぶん、次が出せるようになる。
         遅いと取り損ねたカプセルが枠を占有し続けて供給が詰まる */
      capsuleSpeed: -66,
      bellFloat: -46,       // ベルは撃つと浮き上がる（ツインビー式）
      bellFall: 26,
      life: 13              // アイテムの寿命（秒）
    },

    /* ---------- 演出 ---------- */
    fx: {
      /* 画面揺れは使わない。
         狙って動かす操作の最中に画面ごと動くと、自機と敵弾の位置が
         読み取りにくくなる。手応えはヒットストップ・閃光・衝撃波リングで出す。
         （true にすれば揺れは復活する） */
      shake: false,
      shakeMax: 14,
      hitStopBig: 0.055,    // 大型撃破時に止める秒数（手応えを作る）
      starLayers: 3
    },

    /* ---------- 音 ---------- */
    audio: {
      master: 0.42,
      bgm: 0.30,
      bpm: 152
    }
  };

  /* ---------------------------------------------------------
     以下は CFG から導出される「バランスが崩れていないか」を
     自分で説明するための関数。README の数字はここから来ている。
     --------------------------------------------------------- */

  /* 難易度カーブを 1 本の式で評価する。
     base から per ずつ増え（減り）、max / min で頭打ちになる */
  function ramp(c, wave) {
    var v = c.base + c.per * wave;
    if (c.max !== undefined) v = Math.min(c.max, v);
    if (c.min !== undefined) v = Math.max(c.min, v);
    return v;
  }
  CFG.ramp = ramp;

  /* 実効ウェーブ。経過時間に、自機の装備の充実度を足したもの。
     脅威側のパラメータはすべてこの値で評価する */
  CFG.threatWave = function (G) {
    var ratio = (w.Weapons && G.pw) ? Weapons.powerRatio(G.pw) : 0;
    return G.wave + ratio * CFG.threatFromPower;
  };

  CFG.bulletBudget = function (tw) { return Math.round(ramp(CFG.curve.budget, tw)); };
  CFG.enemyBulletSpeed = function (tw) { return ramp(CFG.curve.speed, tw); };
  CFG.aimError = function (tw) { return ramp(CFG.curve.aim, tw); };
  CFG.armedMax = function (tw) { return Math.round(ramp(CFG.curve.armed, tw)); };
  CFG.toughness = function (tw) { return ramp(CFG.curve.tough, tw); };
  CFG.armedMix = function (tw) { return ramp(CFG.curve.armedMix, tw); };
  CFG.killsPerCapsule = function (wave) { return Math.round(ramp(CFG.item.killsPerCapsule, wave)); };

  /* そのウェーブでの敵の湧き間隔（秒） */
  CFG.spawnInterval = function (wave) {
    var d = CFG.director;
    return Math.max(d.intervalFloor, d.baseInterval * Math.pow(d.intervalDecay, wave));
  };

  /* そのウェーブでの 1 編隊あたりの敵数 */
  CFG.spawnCount = function (wave) {
    var d = CFG.director;
    return Math.min(d.countMax, Math.round(d.baseCount + wave * d.countPerWave));
  };

  /* 1 秒あたりに湧く敵の数（＝密度の指標）。時間とともに増える */
  CFG.enemiesPerSecond = function (wave) {
    return CFG.spawnCount(wave) / CFG.spawnInterval(wave);
  };

  w.CFG = CFG;
})(window);
