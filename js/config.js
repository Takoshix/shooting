/* =========================================================
   config.js — ゲームバランスの全パラメータと、その設計思想
   ---------------------------------------------------------
   このゲームの目的は「敵はどんどん増えるが、難易度は上がらない。
   武器が強くなって爽快感だけが増えていく」こと。
   普通のシューティングは時間とともに敵が強く・速く・弾が多くなるが、
   ここでは逆に「敵の密度」だけを上げ、「危険度」は一定に保つ。

   そのために 5 つの安全装置を入れている。

   (1) 弾幕予算（bullet budget）
       画面上に存在できる敵弾の総数に上限を設ける。敵が 5 匹でも 200 匹でも
       上限は同じ。敵が増えるほど 1 匹あたりの発射確率が自動的に下がるので、
       「撃たれる量」は最初から最後までほぼ一定になる。

   (1b) 脅威の総量を 2 方向から固定する
       弾を抑えても、敵が増えれば「体当たり」の危険が増えてしまう。
       これを塞がないと結局は難しくなる。そこで敵を 2 種類に分ける。
         ・ザコ（HP 2 以下）… いくら増えても自機に当たっても壊れるだけ。
                               自機は無傷で、むしろ得点になる。
         ・武装敵（HP 3 以上）… 自機を破壊しうるが、画面内の数に上限を設ける。
       つまり「増えるのは無害な敵だけ」「危険な敵と弾の数は一定」。
       これで敵の総数が 10 倍になっても、危険の総量は変わらない。

   (2) 敵弾スピード・狙いのブレを固定
       弾速も、自機を狙う精度も、最後まで変えない。反応時間の要求が
       上がらない＝プレイヤーの腕への要求が上がらない。

   (3) 敵の耐久力（HP）を絶対に上げない
       増えるのは「数」だけ。1 匹あたりの撃破時間（TTK: Time To Kill）は
       むしろ武器強化で短くなっていく。

   (4) 撃破数に比例したパワーアップ供給
       一定数倒すごとに必ずパワーカプセルが出る。敵が増える
       ＝供給が増える＝武器が強くなる。密度上昇が自動的に火力上昇になる。

   (5) チェイン（連鎖）による自動火力ブースト
       短時間に倒し続けるほど連射速度が上がり、追加のサイドショットが出る。
       敵が多いほど連鎖が途切れない＝敵が多いほど自機が強い、という
       自己平衡（セルフバランス）が働く。

   さらにミス時のペナルティも軽い（グラディウス式の「全パワー喪失」はしない）。
   死ぬたびに弱くなると、そこが難易度の山になってしまうため。
   ========================================================= */
(function (w) {
  'use strict';

  var CFG = {
    /* ---------- 画面 ---------- */
    W: 640,            // 論理解像度（CSS で拡大表示する）
    H: 400,
    FPS: 60,
    DT: 1 / 60,        // 固定タイムステップ（1 フレームの秒数）

    /* ---------- 自機 ---------- */
    player: {
      x: 90, y: 200,
      r: 3.5,          // 当たり判定半径。見た目より小さい（被弾ストレスを下げる）
      drawR: 12,
      baseSpeed: 195,  // px/秒
      speedStep: 46,   // SPEED を 1 段取るごとの上昇量
      speedMax: 4,     // SPEED の最大段数
      slowRate: 0.42,  // Shift 低速時の倍率
      invincible: 2.2, // ミス後の無敵秒数
      respawn: 0.9     // ミス後の復帰待ち秒数
    },

    /* ---------- 自機の武器 ---------- */
    weapon: {
      fireInterval: 0.105,   // ショット間隔（秒）
      fireIntervalMin: 0.058,// チェイン最大時の間隔。ここまで速くなる
      bulletSpeed: 660,
      bulletDamage: 1,

      doubleMax: 3,          // DOUBLE の最大段数（1:2way 2:3way 3:5way）
      laserMax: 3,           // LASER の最大段数
      missileMax: 3,         // MISSILE の最大段数
      missileInterval: 0.52,
      missileDamage: 3,

      optionMax: 4,          // オプション（マルチプル）最大数
      optionGap: 11,         // オプション同士の距離（自機の軌跡を何フレーム遡るか）

      shieldHits: 5          // フォースフィールド 1 回あたりの耐弾数
    },

    /* パワーメーター（グラディウス方式）のスロット。
       カプセルを取るとカーソルが 1 つ進み、X で発動して消費する。 */
    slots: [
      { key: 'speed',   label: 'SPEED',   color: '#7fe3ff' },
      { key: 'missile', label: 'MISSILE', color: '#ffd45e' },
      { key: 'double',  label: 'DOUBLE',  color: '#7dff9a' },
      { key: 'laser',   label: 'LASER',   color: '#ff7ad1' },
      { key: 'option',  label: 'OPTION',  color: '#b79cff' },
      { key: 'force',   label: 'FORCE',   color: '#ff8f5e' }
    ],

    /* ---------- チェイン（連鎖） ---------- */
    chain: {
      hold: 2.0,        // 最後の撃破からこの秒数で連鎖が切れる
      max: 300,         // 表示・計算上の上限
      rateAt: 120,      // この連鎖数で連射速度が最大になる
      side1: 30,        // この連鎖数から上下へサイドショット追加
      side2: 90,        // さらに追加
      scoreStep: 25     // 25 連鎖ごとに得点倍率 +1
    },

    /* ---------- ボム ---------- */
    bomb: {
      start: 2,
      max: 5,
      damage: 40,       // 画面内の敵全体に与えるダメージ
      duration: 0.8
    },

    /* =========================================================
       ▼ ここから下が「難易度を上げない」ための安全装置
       ========================================================= */

    threat: {
      /* (1) 弾幕予算：画面に出せる敵弾の上限。時間が経っても増えない */
      bulletBudget: 18,

      /* (2) 敵弾は最後まで同じ速さ・同じ精度 */
      bulletSpeed: 118,     // px/秒（自機の移動より遅い＝必ず避けられる）
      aimError: 0.17,       // 狙い撃ちのブレ幅（ラジアン）。縮まない

      /* 予算の何割まで埋まったら発射を渋り始めるか。
         これにより敵が増えても「空中の弾の数」がほぼ一定に保たれる */
      softCapRatio: 0.7,

      /* 敵が密集しすぎたときに自機の周囲へは湧かせない安全半径 */
      spawnSafeR: 96,

      /* (1b) 自機を破壊しうる「武装敵」の画面内上限。ここも時間で増えない。
         これを超える分はザコに差し替えられる（数は減らさず危険だけ抑える） */
      armoredMax: 8,

      /* 体当たりしても自機が壊れない敵の HP しきい値。
         これ以下の敵は “無害な的” として好きなだけ増やせる */
      harmlessHp: 2
    },

    /* ---------- 敵の湧き（ディレクター） ---------- */
    director: {
      waveSeconds: 16,      // この秒数ごとに「密度」が 1 段上がる
      baseInterval: 2.0,    // 編隊を出す間隔（秒）
      intervalFloor: 0.36,  // どれだけ詰まってもこれ以上は速くしない
      intervalDecay: 0.865, // ウェーブごとに間隔へ掛ける係数
      baseCount: 3,         // 1 編隊あたりの初期数
      countPerWave: 1.9,    // ウェーブごとの増加数
      countMax: 34,         // 1 編隊の最大数
      aliveMax: 260,        // 画面内の敵の最大数（処理落ち防止のみが目的）
      bossEvery: 6          // このウェーブ数ごとに大型艦（ご褒美タイム）
    },

    /* ---------- アイテム ---------- */
    item: {
      /* (4) 撃破数に比例した供給：この数だけ倒すたびに必ずカプセルが出る。
         敵が増える → 供給が増える → 火力が上がる、という直結を作る */
      capsulePerKills: 14,

      /* ただし供給には上限も要る。毎秒 100 匹倒す終盤に撃破数だけで配ると
         毎秒 7 個も降ってきてメーターのカーソルが制御不能になり、
         「好きな装備を選ぶ」というグラディウスの遊びが壊れる。
         そこで落下間隔と画面内の数に上限を設ける（強さの伸びは
         チェインとオプションが担うので、ここを絞っても爽快感は落ちない） */
      capsuleMinInterval: 0.55,
      capsuleOnScreenMax: 8,
      capsuleSpeed: -52,    // 左へゆっくり流れる
      bellFloat: -46,       // ベルは撃つと浮き上がる（ツインビー式）
      bellFall: 26,
      life: 11              // アイテムの寿命（秒）
    },

    /* ---------- 演出 ---------- */
    fx: {
      shakeMax: 14,
      hitStopBig: 0.055,    // 大型撃破時に止める秒数（手応えを作る）
      starLayers: 3
    },

    /* ---------- 音 ---------- */
    audio: {
      master: 0.42,
      bgm: 0.30,
      bpm: 152
    }
  };

  /* ---------------------------------------------------------
     以下は CFG から導出される「バランスが崩れていないか」を
     自分で説明するための関数。README の数字はここから来ている。
     --------------------------------------------------------- */

  /* そのウェーブでの敵の湧き間隔（秒） */
  CFG.spawnInterval = function (wave) {
    var d = CFG.director;
    return Math.max(d.intervalFloor, d.baseInterval * Math.pow(d.intervalDecay, wave));
  };

  /* そのウェーブでの 1 編隊あたりの敵数 */
  CFG.spawnCount = function (wave) {
    var d = CFG.director;
    return Math.min(d.countMax, Math.round(d.baseCount + wave * d.countPerWave));
  };

  /* 1 秒あたりに湧く敵の数（＝密度の指標）。時間とともに増える */
  CFG.enemiesPerSecond = function (wave) {
    return CFG.spawnCount(wave) / CFG.spawnInterval(wave);
  };

  w.CFG = CFG;
})(window);
